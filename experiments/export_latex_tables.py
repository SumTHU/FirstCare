# -*- coding: utf-8 -*-
"""Task 7.3：评测结果 JSON → Springer LNCS LaTeX 表格一键导出。

当前范围（经确认收窄）：仅导出端到端整体 Pipeline 评分（Table 2）。
检索消融（RRF/LoRA 负结果）与三态核验评测不在本脚本范围。

用法：
    python -m experiments.export_latex_tables
    python -m experiments.export_latex_tables --out out/table2.tex
"""

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import CACHE_DIR

EVAL_JSON = CACHE_DIR / "eval_results" / "pipeline_eval.json"
DEFAULT_OUT = PROJECT_ROOT / "out" / "table2_pipeline_eval.tex"

CAT_ZH = {
    "fever": "发热", "abdominal_pain": "腹痛",
    "red_flag_dyspnea": "红旗·呼吸困难", "red_flag_chest_pain": "红旗·胸痛",
    "red_flag_headache": "红旗·头痛", "red_flag_consciousness": "红旗·意识改变",
}


def fmt(v, nd=1):
    return "--" if v is None else f"{v:.{nd}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--eval-json", default=str(EVAL_JSON))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()

    data = json.loads(Path(args.eval_json).read_text(encoding="utf-8"))
    s = data.get("summary")
    if not s:
        sys.exit("结果 JSON 无 summary（评测未完成？）")

    veto = s["veto_rate_pct"]
    rows = [
        ("样本数（评分成功）", f"{s['n_scored']}", "--"),
        ("R1-R6 总分均值（100 分制）", fmt(s["mean_total_100"]), "--"),
        ("红旗组总分均值", fmt(s["mean_total_redflag"]), "硬指标组"),
        ("非红旗组总分均值", fmt(s["mean_total_nonred"]), "--"),
        ("Veto 1 伪造病例率 (\\%)", fmt(veto["v1_fabricated_case"]), "须为 0"),
        ("Veto 2 反向致命结论率 (\\%)", fmt(veto["v2_dangerous_direction"]), "红旗组须为 0"),
        ("Veto 3 违规处方率 (\\%)", fmt(veto["v3_unsafe_prescription"]), "须为 0"),
        ("Veto 4 捏造患者事实率 (\\%)", fmt(veto["v4_fabricated_facts"]), "防线：双栏拆分+数值守卫"),
        ("红旗组 Veto 2 计数", f"{s['redflag_veto2_count']}", "硬性指标 = 0"),
        ("红旗组“立即急诊”判定率 (\\%)", fmt(s["redflag_urgency_emergency_rate"]), "越接近 100 越好"),
        ("Gold 病例精排 Top-1 命中率 (\\%)", fmt(s["gold_top1_after_rerank"]), "参考指标"),
        ("引用病例编号有效率 (\\%)", fmt(s["cited_valid_rate"]), "Veto 1 确定性校验"),
        ("LLM 生成模式占比 (\\%)", fmt(
            (s["gen_mode_dist"].get("llm", 0)) / max(s["n_scored"], 1) * 100, 1),
         "回落模板的样本计入 template"),
    ]

    lines = [
        "% Auto-generated by experiments/export_latex_tables.py — do not cite numbers manually.",
        "% Source: " + str(args.eval_json),
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{端到端整体管线评分（CMCR-Colloquial 分层抽样，LLM 裁判两层量表）。"
        "裁判与生成器共用模型池，分数存在自我偏好风险，仅作相对参考。}",
        "\\label{tab:pipeline-eval}",
        "\\begin{tabular}{lrl}",
        "\\hline",
        "\\textbf{指标} & \\textbf{数值} & \\textbf{说明} \\\\",
        "\\hline",
    ]
    for name, val, note in rows:
        lines.append(f"{name} & {val} & {note} \\\\")
    lines.append("\\hline")
    if s.get("per_category_mean"):
        lines.append("\\multicolumn{3}{l}{\\textit{症候群分层均值}} \\\\")
        for cat, v in s["per_category_mean"].items():
            lines.append(f"\\quad {CAT_ZH.get(cat, cat)} & {fmt(v['mean'])} & n={v['n']} \\\\")
        lines.append("\\hline")
    lines += ["\\end{tabular}", "\\end{table}"]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"LaTeX 表格已导出: {out}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
